(function () {
  const STORAGE_KEY = "clr_lang";

  function applyLang(lang) {
    const dict = I18N[lang] || I18N.en;
    document.documentElement.setAttribute("lang", lang);
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (dict[key]) el.innerHTML = dict[key];
    });
    document.querySelectorAll("[data-lang-label]").forEach((el) => {
      el.textContent = lang.toUpperCase();
    });
    localStorage.setItem(STORAGE_KEY, lang);
  }

  function initLangSwitch() {
    const saved = localStorage.getItem(STORAGE_KEY) || "en";
    applyLang(saved);

    document.querySelectorAll(".lang-switch").forEach((widget) => {
      const btn = widget.querySelector(".lang-btn");
      btn.addEventListener("click", (e) => {
        e.stopPropagation();
        document.querySelectorAll(".lang-switch").forEach((w) => {
          if (w !== widget) w.classList.remove("open");
        });
        widget.classList.toggle("open");
      });
      widget.querySelectorAll(".lang-menu button").forEach((opt) => {
        opt.addEventListener("click", () => {
          applyLang(opt.getAttribute("data-lang"));
          widget.classList.remove("open");
        });
      });
    });
    document.addEventListener("click", () => {
      document.querySelectorAll(".lang-switch.open").forEach((w) => w.classList.remove("open"));
    });
  }

  document.addEventListener("DOMContentLoaded", initLangSwitch);
})();
